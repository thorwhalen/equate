"""Self-benchmarking: a benchmark registry and an honest-by-default harness.

:func:`benchmark_matcher` is where "measure honestly" becomes the path of least
resistance (research doc 14, §8.4): it splits **by entity** so test entities are unseen,
fits a trainable matcher on train only (and asserts the split did not leak), scores the
test part only, reports the test **base rate** and a **cost column** (wall-clock seconds)
next to every score, and repeats over seeds so a number comes with its spread. A seed
whose test part holds no gold pair is skipped with a warning rather than scored as a
vacuous perfect 1.0.

The scores are **pairwise** (precision, recall, F1). B³ is deliberately not reported for
a two-table matching: every unmatched record is a singleton there, and singletons score
well under B³ whatever the matcher did — an empty prediction would read ~0.75.

Benchmarks are a registry, so adding one is registering a loader, not editing the core.
The built-in ``toy_names`` is generated (no download, deterministic): enough to exercise a
matcher and this harness in CI. The standard suites — ``abt_buy``, ``amazon_google``,
``dblp_acm`` and ``wdc_products`` — are registered by :mod:`equate.evaluate.suites` and
download on first use into a store (:mod:`equate.evaluate.store`), never the package.

A benchmark that ships its own **canonical split** (WDC Products' unseen-entity test sets)
carries it in ``Benchmark.splits``, and :func:`benchmark_matcher` uses it by default
(``split='auto'``): the suite's designers chose those test sets to control difficulty, and
published numbers are measured on them.
"""

import time
import warnings
from collections.abc import Callable, Iterable, Sequence
from dataclasses import dataclass, field
from typing import Optional

import numpy as np

from equate.evaluate.labels import cross_pairs_to_labels
from equate.evaluate.metrics import pairwise_prf
from equate.evaluate.split import assert_no_leakage, entity_split
from equate.registry import Registry


@dataclass(frozen=True)
class Benchmark:
    """Two collections and the gold correspondence between them.

    ``gold`` holds ``(i, j)`` pairs: ``a[i]`` corresponds to ``b[j]``. ``meta`` carries
    what a reader needs next to a score — at least ``source`` and ``difficulty``.

    Optional, when the suite defines them:

    - ``splits`` — the suite's canonical record split, ``{'train'|'val'|'test':
      (a_indices, b_indices)}``;
    - ``pairs`` — the suite's labelled candidate pairs, ``{'train'|'val'|'test':
      ((i, j, label), ...)}`` (the DeepMatcher pair-classification task).
    """

    name: str
    a: Sequence
    b: Sequence
    gold: frozenset
    meta: dict = field(default_factory=dict)
    splits: Optional[dict] = None
    pairs: Optional[dict] = None

    @property
    def base_rate(self) -> float:
        """Share of all ``a × b`` pairs that are true matches."""
        total = len(self.a) * len(self.b)
        return len(self.gold) / total if total else 0.0


#: name -> factory(**config) returning a :class:`Benchmark`
benchmarks = Registry("benchmark")


def _toy_names(
    *, n_entities: int = 60, n_distractors: int = 20, seed: int = 0
) -> Benchmark:
    """Generated person-like names; ``b`` holds a typo'd copy of each plus distractors."""
    rng = np.random.default_rng(seed)
    syllables = ["ka", "lo", "mi", "ra", "to", "ve", "su", "ni", "da", "pe", "zo", "ri"]

    used: set = set()

    def name():
        # unique across a AND b, and never equal to a typo'd copy, so gold is unambiguous
        while True:
            first = "".join(rng.choice(syllables, size=rng.integers(2, 4)))
            last = "".join(rng.choice(syllables, size=rng.integers(2, 4)))
            s = f"{first.title()} {last.title()}"
            if s not in used:
                used.add(s)
                return s

    def typo(s):
        i = int(rng.integers(1, len(s) - 1))
        op = rng.integers(3)
        if op == 0:
            return s[:i] + s[i + 1 :]  # drop a character
        if op == 1:
            return s[:i] + s[i] + s[i:]  # double one
        return s[: i - 1] + s[i] + s[i - 1] + s[i + 1 :]  # swap two

    a = [name() for _ in range(n_entities)]
    b_true = []
    for s in a:
        t = typo(s)
        while t in used:
            t = typo(s)
        used.add(t)
        b_true.append(t)
    b_all = b_true + [name() for _ in range(n_distractors)]
    order = rng.permutation(len(b_all))
    position = {int(old): new for new, old in enumerate(order)}
    b = [b_all[int(old)] for old in order]
    gold = frozenset((i, position[i]) for i in range(n_entities))
    return Benchmark(
        "toy_names",
        a,
        b,
        gold,
        meta={
            "source": "generated by equate (no download)",
            "difficulty": "easy: one character edit per true pair, random distractors",
        },
    )


benchmarks.register("toy_names", _toy_names)


def list_benchmarks() -> list[str]:
    """Names of the registered benchmarks."""
    return benchmarks.names()


def load_benchmark(name: str, **config) -> Benchmark:
    """Build a registered benchmark (``config`` goes to its loader)."""
    return benchmarks.create(name, **config)


@dataclass(frozen=True)
class BenchmarkRow:
    """One (benchmark, seed) run: the scores, their context, and what they cost."""

    benchmark: str
    seed: int
    precision: float
    recall: float
    f1: float
    seconds: float
    n_a: int
    n_b: int
    n_gold: int
    base_rate: float


@dataclass(frozen=True)
class BenchmarkReport:
    """All runs, plus a per-benchmark summary of mean ± std over seeds."""

    rows: tuple
    meta: dict = field(default_factory=dict)

    _METRICS = ("precision", "recall", "f1", "seconds")

    def summary(self) -> dict:
        """``{benchmark: {metric: (mean, std), 'base_rate': mean, 'n_seeds': k}}``."""
        out: dict = {}
        for name in dict.fromkeys(r.benchmark for r in self.rows):
            rows = [r for r in self.rows if r.benchmark == name]
            stats = {
                m: (
                    float(np.mean([getattr(r, m) for r in rows])),
                    float(np.std([getattr(r, m) for r in rows])),
                )
                for m in self._METRICS
            }
            stats["base_rate"] = float(np.mean([r.base_rate for r in rows]))
            stats["n_seeds"] = len(rows)
            out[name] = stats
        return out

    def to_markdown(self) -> str:
        """One row per benchmark: precision, recall, F1, seconds, base rate, difficulty."""
        head = "| benchmark | precision | recall | F1 | seconds | test base rate | seeds | difficulty |"
        lines = [head, "|" + "---|" * 8]
        for name, s in self.summary().items():
            cells = [f"{s[m][0]:.3f} ± {s[m][1]:.3f}" for m in self._METRICS]
            difficulty = self.meta.get(name, {}).get("difficulty", "")
            lines.append(
                f"| {name} | "
                + " | ".join(cells)
                + f" | {s['base_rate']:.4f} | {s['n_seeds']} | {difficulty} |"
            )
        return "\n".join(lines)


def subset_pairs(gold, rows_a, rows_b):
    """Gold pairs with both ends in the subset, re-indexed into the subset.

    >>> sorted(subset_pairs({(0, 1), (2, 0)}, [2, 0], [0, 1]))
    [(0, 0), (1, 1)]
    """
    ia = {old: new for new, old in enumerate(rows_a)}
    ib = {old: new for new, old in enumerate(rows_b)}
    return {(ia[i], ib[j]) for i, j in gold if i in ia and j in ib}


_SPLIT_MODES = ("auto", "entity", "canonical")


def _use_canonical(ds, split):
    if split not in _SPLIT_MODES:
        raise ValueError(f"split must be one of {_SPLIT_MODES}, got {split!r}")
    if split == "canonical" and not ds.splits:
        raise ValueError(f"{ds.name} has no canonical split; use split='entity'")
    return split == "canonical" or (split == "auto" and bool(ds.splits))


def _parts(ds, entity, side, canonical, n_seeds, ratios):
    """Yield ``(seed, ((train_a, train_b), (val_a, val_b), (test_a, test_b)))``."""
    if canonical:
        yield (
            0,
            tuple(
                tuple(list(x) for x in ds.splits.get(name, ((), ())))
                for name in ("train", "val", "test")
            ),
        )
        return
    for seed in range(n_seeds):
        s = entity_split(entity, ratios=ratios, seed=seed)
        assert_no_leakage(entity, s.train, s.val, s.test)
        yield seed, (side(s.train), side(s.val), side(s.test))


def benchmark_matcher(
    matcher: Optional[Callable] = None,
    *,
    on: Iterable = ("toy_names",),
    n_seeds: int = 3,
    ratios: tuple = (0.6, 0.2, 0.2),
    fit: Optional[Callable] = None,
    split: str = "auto",
) -> BenchmarkReport:
    """Score ``matcher`` on unseen-entity test splits of each benchmark in ``on``.

    ``matcher(a, b)`` returns ``(i, j)`` pairs (a :class:`~equate.base.Matching`
    qualifies); the default is :func:`equate.match`. ``on`` is a benchmark name, a
    :class:`Benchmark`, or an iterable of either. Scores are pairwise; a seed whose test
    part has no gold pair is skipped with a warning, and a benchmark with no scorable
    seed is an error. For each of ``n_seeds`` seeds the records of ``a + b``
    are split by entity (``ratios`` = train/val/test); only the **test** part is
    matched and scored, so a test entity was never seen in training.

    ``fit(train_a, train_b, train_pairs, val_a, val_b, val_pairs) -> matcher`` makes the
    harness train per seed: it gets the train and validation parts only (the split is
    asserted leak-free first), and the matcher it returns is scored on test. Choose a
    threshold on the validation part there (:func:`~equate.evaluate.select_threshold`),
    never on test.

    ``split`` chooses the parts: ``'entity'`` is the seeded entity split above;
    ``'canonical'`` uses the benchmark's own ``splits`` (one run, ``n_seeds`` and
    ``ratios`` ignored; no entity-leakage assertion, since a suite's *seen-entity*
    variants share entities across parts by design); ``'auto'`` (default) is canonical
    when the benchmark has ``splits``, else entity.

    >>> report = benchmark_matcher(n_seeds=2)
    >>> s = report.summary()['toy_names']
    >>> s['f1'][0] > 0.8, s['n_seeds']
    (True, 2)
    """
    if matcher is not None and fit is not None:
        raise ValueError(
            "pass either matcher or fit (which returns the matcher), not both"
        )
    if matcher is None and fit is None:
        from equate.facade import match as matcher
    if isinstance(on, (str, Benchmark)):
        on = [on]
    rows, meta = [], {}
    for spec in on:
        ds = spec if isinstance(spec, Benchmark) else load_benchmark(spec)
        meta[ds.name] = dict(ds.meta)
        n_a, n_b = len(ds.a), len(ds.b)
        entity = cross_pairs_to_labels(ds.gold, n_a=n_a, n_b=n_b)

        def side(records):
            return (
                [i for i in records if i < n_a],
                [i - n_a for i in records if i >= n_a],
            )

        canonical = _use_canonical(ds, split)
        meta[ds.name]["split"] = "canonical" if canonical else "entity"
        scored = 0
        for seed, parts in _parts(ds, entity, side, canonical, n_seeds, ratios):
            (tr_a, tr_b), (va_a, va_b), (test_a, test_b) = parts
            gold = subset_pairs(ds.gold, test_a, test_b)
            if not gold:
                warnings.warn(
                    f"{ds.name} seed {seed}: the test part holds no gold pair "
                    f"({len(test_a)} x {len(test_b)} records) — skipped, not scored as 1.0"
                )
                continue
            run = matcher
            if fit is not None:
                run = fit(
                    [ds.a[i] for i in tr_a],
                    [ds.b[j] for j in tr_b],
                    subset_pairs(ds.gold, tr_a, tr_b),
                    [ds.a[i] for i in va_a],
                    [ds.b[j] for j in va_b],
                    subset_pairs(ds.gold, va_a, va_b),
                )
            start = time.perf_counter()
            pred = {
                tuple(p)
                for p in run([ds.a[i] for i in test_a], [ds.b[j] for j in test_b])
            }
            seconds = time.perf_counter() - start
            s = pairwise_prf(pred, gold)
            n_ta, n_tb = len(test_a), len(test_b)
            rows.append(
                BenchmarkRow(
                    ds.name,
                    seed,
                    s.precision,
                    s.recall,
                    s.f1,
                    seconds,
                    n_ta,
                    n_tb,
                    len(gold),
                    len(gold) / (n_ta * n_tb),
                )
            )
            scored += 1
        if not scored:
            raise ValueError(
                f"{ds.name}: its canonical test part holds no gold pair"
                if canonical
                else f"{ds.name}: no seed produced a test part with a gold pair; the "
                f"benchmark is too small for ratios={ratios!r}"
            )
    return BenchmarkReport(tuple(rows), meta)
